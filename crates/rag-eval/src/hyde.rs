//! Bounty #24 (`hanzoai/index#28`): Hypothetical-Document Retrieval (`HyDE`).
//!
//! Clean-room Apache-2.0 Rust implementation of Hypothetical Document Embeddings
//! (Gao et al., ACL 2023, arXiv:2212.10496; reference repo `texttron/hyde` under
//! Apache-2.0) paired with HIP-1346 §1 immutable `doc_prefix` / `query_prefix`
//! enforcement and HIP-1346 §2 Kai-decides / Zen-synthesizes stack boundaries:
//!
//! - **Zen** (`ZenHypothesisGenerator`) synthesizes ephemeral hypothetical
//!   passages for vocabulary-mismatched queries. Synthetic passages are never
//!   persisted into a canonical source index (`EphemeralHypothesisInsertForbidden`).
//! - **HIP-1346 §1 Immutable Prefix Contract** (`ImmutableIndexContract`):
//!   stored corpus vectors are strictly encoded with `doc_prefix` and validated
//!   via `IndexOperation::Insert`, query vectors are encoded with `query_prefix`
//!   and validated via `IndexOperation::Query`, and differently prefixed inputs
//!   are never mixed inside one collection.
//! - **Kai** (`KaiHydeGate` + `KaiHydeClassifier`) emits structured discrete
//!   routing probabilities (`expand_with_hyde` vs `query_only`) so exact symbol
//!   or identifier lookups avoid unnecessary Zen generation latency, token cost,
//!   and rare-identifier drift.

