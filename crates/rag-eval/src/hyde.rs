/// Prefix-enforced, tenant-isolated in-memory vector index for HyDE evaluation
/// and retrieval gating under HIP-1346 §1.
#[derive(Debug, Clone, Default)]
pub struct HydeIndex {
    contract: ImmutableIndexContract,
    records: BTreeMap<String, Vec<StoredVectorRecord>>,
}

impl HydeIndex {
    /// Creates an empty `HydeIndex` backed by an `ImmutableIndexContract`.
    pub fn new() -> Self {
        Self::default()
    }

    /// Exposes the underlying `ImmutableIndexContract`.
    pub fn contract(&self) -> &ImmutableIndexContract {
        &self.contract
    }

    /// Registers a collection with immutable embedding metadata.
    pub fn register_collection(
        &mut self,
        collection: impl Into<String>,
        metadata: IndexEmbeddingMetadata,
    ) -> Result<(), HydeError> {
        let name = collection.into();
        self.contract.register(name.clone(), metadata)?;
        self.records.entry(name).or_default();
        Ok(())
    }

    /// Returns the number of canonical documents stored in `collection`.
    pub fn collection_len(&self, collection: &str) -> usize {
        self.records.get(collection).map_or(0, Vec::len)
    }

    /// Inserts a canonical source document after enforcing:
    /// 1. `DocumentOrigin::CanonicalSource` (ephemeral Zen hypotheses are rejected),
    /// 2. non-empty `doc_id` and `tenant_id`,
    /// 3. rejection of pre-supplied `query_prefix` text so differently prefixed
    ///    vectors are never mixed inside one collection, and
    /// 4. `ImmutableIndexContract::validate_insert` over `doc_prefix` + vector shape/norm.
    pub fn insert_document(
        &mut self,
        collection: &str,
        runtime_meta: &IndexEmbeddingMetadata,
        doc: HydeDocument,
        embedder: &dyn PrefixedTextEmbedder,
    ) -> Result<(), HydeError> {
        if doc.origin == DocumentOrigin::SyntheticHypothesis {
            return Err(HydeError::EphemeralHypothesisInsertForbidden { doc_id: doc.doc_id });
        }
        if doc.doc_id.trim().is_empty() {
            return Err(HydeError::EmptyDocId);
        }
        if doc.tenant_id.trim().is_empty() {
            return Err(HydeError::EmptyTenantId);
        }

        let persisted = self
            .contract
            .get(collection)
            .ok_or_else(|| MetadataError::UnknownCollection(collection.to_string()))?
            .clone();
        persisted.validate_runtime(runtime_meta, IndexOperation::Insert)?;

        reject_pre_swapped_prefix(
            &doc.raw_text,
            &persisted.doc_prefix,
            &persisted.query_prefix,
            IndexOperation::Insert,
            MetadataField::DocPrefix,
            MetadataField::QueryPrefix,
        )?;

        let prefixed_doc = persisted.format_document(&doc.raw_text);
        let vector =
            embedder.embed_prefixed(&prefixed_doc, IndexOperation::Insert, runtime_meta)?;
        self.contract.validate_insert(collection, runtime_meta, &vector, Some(&prefixed_doc))?;

        let bucket = self.records.entry(collection.to_string()).or_default();
        if let Some(existing) =
            bucket.iter_mut().find(|r| r.doc_id == doc.doc_id && r.tenant_id == doc.tenant_id)
        {
            existing.source_revision = doc.source_revision;
            existing.allowed_roles = doc.allowed_roles;
            existing.raw_text = doc.raw_text;
            existing.vector = vector;
        } else {
            bucket.push(StoredVectorRecord {
                doc_id: doc.doc_id,
                source_revision: doc.source_revision,
                tenant_id: doc.tenant_id,
                allowed_roles: doc.allowed_roles,
                raw_text: doc.raw_text,
                vector,
            });
        }
        Ok(())
    }

    /// Executes standard query-only dense retrieval (`query_prefix + raw_query`).
    #[allow(clippy::too_many_arguments)]
    pub fn search_query_only(
        &self,
        collection: &str,
        runtime_meta: &IndexEmbeddingMetadata,
        caller: &CallerAccessContext,
        raw_query: &str,
        top_k: usize,
        embedder: &dyn PrefixedTextEmbedder,
        cost_model: &HydeCostModel,
    ) -> Result<HydeSearchOutcome, HydeError> {
        if raw_query.trim().is_empty() {
            return Err(HydeError::EmptyQuery);
        }
        if caller.tenant_id.trim().is_empty() {
            return Err(HydeError::EmptyTenantId);
        }
        if top_k == 0 {
            return Err(HydeError::ZeroTopK);
        }
        cost_model.validate()?;

        let persisted = self
            .contract
            .get(collection)
            .ok_or_else(|| MetadataError::UnknownCollection(collection.to_string()))?;
        persisted.validate_runtime(runtime_meta, IndexOperation::Query)?;

        reject_pre_swapped_prefix(
            raw_query,
            &persisted.query_prefix,
            &persisted.doc_prefix,
            IndexOperation::Query,
            MetadataField::QueryPrefix,
            MetadataField::DocPrefix,
        )?;

        let prefixed_query = persisted.format_query(raw_query);
        let q_vec =
            embedder.embed_prefixed(&prefixed_query, IndexOperation::Query, runtime_meta)?;
        self.contract.validate_query(collection, runtime_meta, &q_vec, Some(&prefixed_query))?;

        let hits = self.rank_authorized_records(collection, caller, &q_vec, top_k);
        let q_tokens = estimate_tokens(&prefixed_query);
        let total_cost_usd = (q_tokens as f64 / 1000.0) * cost_model.embed_cost_per_1k_tokens_usd;
        let total_latency_ms =
            cost_model.embed_latency_ms_per_call + cost_model.index_search_latency_ms;

        Ok(HydeSearchOutcome {
            route_action: HydeRouteAction::QueryOnly,
            kai_decision: None,
            hits,
            generated_hypotheses: Vec::new(),
            embed_calls: 1,
            zen_generated_tokens: 0,
            total_latency_ms,
            total_cost_usd,
        })
    }

    /// Executes HyDE retrieval:
    /// 1. Synthesizes `num_hypotheses` ephemeral passages with Zen,
    /// 2. Encodes each synthetic passage with `doc_prefix` (validated via
    ///    `IndexOperation::Insert` without storing in the collection),
    /// 3. Optionally anchors with `query_prefix + raw_query` weighted by
    ///    `query_anchor_weight`, re-normalizes under the collection's immutable
    ///    `NormalizationPolicy`, and validates the probe vector, and
    /// 4. Scores only records authorized for `caller`.
    #[allow(clippy::too_many_arguments)]
    pub fn search_hyde(
        &self,
        collection: &str,
        runtime_meta: &IndexEmbeddingMetadata,
        caller: &CallerAccessContext,
        raw_query: &str,
        config: &HydeConfig,
        generator: &dyn ZenHypothesisGenerator,
        embedder: &dyn PrefixedTextEmbedder,
        cost_model: &HydeCostModel,
    ) -> Result<HydeSearchOutcome, HydeError> {
        if raw_query.trim().is_empty() {
            return Err(HydeError::EmptyQuery);
        }
        if caller.tenant_id.trim().is_empty() {
            return Err(HydeError::EmptyTenantId);
        }
        config.validate()?;
        cost_model.validate()?;

        let persisted = self
            .contract
            .get(collection)
            .ok_or_else(|| MetadataError::UnknownCollection(collection.to_string()))?;
        persisted.validate_runtime(runtime_meta, IndexOperation::Query)?;

        reject_pre_swapped_prefix(
            raw_query,
            &persisted.query_prefix,
            &persisted.doc_prefix,
            IndexOperation::Query,
            MetadataField::QueryPrefix,
            MetadataField::DocPrefix,
        )?;

        let hypotheses = generator.generate_hypotheses(raw_query, config.num_hypotheses)?;
        if hypotheses.len() != config.num_hypotheses {
            return Err(HydeError::HypothesisCountMismatch {
                expected: config.num_hypotheses,
                actual: hypotheses.len(),
            });
        }

        let dims = persisted.dimensions;
        let mut passage_mean = vec![0.0_f32; dims];
        let mut embed_tokens_total = 0usize;
        let mut zen_generated_tokens = 0usize;
        let mut max_zen_latency_ms = 0.0_f64;

        for (idx, hyp) in hypotheses.iter().enumerate() {
            if hyp.raw_passage.trim().is_empty() {
                return Err(HydeError::EmptyHypotheticalPassage { index: idx });
            }
            reject_pre_swapped_prefix(
                &hyp.raw_passage,
                &persisted.doc_prefix,
                &persisted.query_prefix,
                IndexOperation::Insert,
                MetadataField::DocPrefix,
                MetadataField::QueryPrefix,
            )?;

            let prefixed_passage = persisted.format_document(&hyp.raw_passage);
            let h_vec =
                embedder.embed_prefixed(&prefixed_passage, IndexOperation::Insert, runtime_meta)?;
            self.contract.validate_insert(
                collection,
                runtime_meta,
                &h_vec,
                Some(&prefixed_passage),
            )?;

            for (acc, &val) in passage_mean.iter_mut().zip(h_vec.iter()) {
                *acc += val;
            }
            embed_tokens_total += estimate_tokens(&prefixed_passage);
            zen_generated_tokens += hyp.generated_tokens.max(estimate_tokens(&hyp.raw_passage));
            if hyp.zen_latency_ms.is_finite() && hyp.zen_latency_ms > max_zen_latency_ms {
                max_zen_latency_ms = hyp.zen_latency_ms;
            }
        }

        let inv_k = 1.0 / (hypotheses.len() as f32);
        for val in &mut passage_mean {
            *val *= inv_k;
        }

        let mut embed_calls = hypotheses.len();
        let prefixed_query = persisted.format_query(raw_query);
        let mut centroid = if config.query_anchor_weight > 0.0 {
            let q_vec =
                embedder.embed_prefixed(&prefixed_query, IndexOperation::Query, runtime_meta)?;
            self.contract.validate_query(
                collection,
                runtime_meta,
                &q_vec,
                Some(&prefixed_query),
            )?;
            embed_calls += 1;
            embed_tokens_total += estimate_tokens(&prefixed_query);

            let w_q = config.query_anchor_weight;
            let w_h = 1.0 - w_q;
            q_vec
                .iter()
                .zip(passage_mean.iter())
                .map(|(&qv, &hv)| w_q * qv + w_h * hv)
                .collect::<Vec<f32>>()
        } else {
            passage_mean
        };

        if persisted.normalization == NormalizationPolicy::L2 {
            let norm_sq: f64 = centroid.iter().map(|&v| f64::from(v) * f64::from(v)).sum();
            let norm = norm_sq.sqrt() as f32;
            if !norm.is_finite() || norm <= 1e-12 {
                return Err(HydeError::ZeroCentroidNorm);
            }
            for v in &mut centroid {
                *v /= norm;
            }
        }
        persisted.validate_vector(&centroid, IndexOperation::Query)?;

        let hits = self.rank_authorized_records(collection, caller, &centroid, config.top_k);
        let zen_prompt_tokens = estimate_tokens(raw_query) * hypotheses.len();
        let total_cost_usd = (embed_tokens_total as f64 / 1000.0)
            * cost_model.embed_cost_per_1k_tokens_usd
            + (zen_prompt_tokens as f64 / 1000.0) * cost_model.zen_input_cost_per_1k_tokens_usd
            + (zen_generated_tokens as f64 / 1000.0) * cost_model.zen_output_cost_per_1k_tokens_usd;
        let total_latency_ms = max_zen_latency_ms
            + (embed_calls as f64) * cost_model.embed_latency_ms_per_call
            + cost_model.index_search_latency_ms;

        Ok(HydeSearchOutcome {
            route_action: HydeRouteAction::HydeExpanded,
            kai_decision: None,
            hits,
            generated_hypotheses: hypotheses,
            embed_calls,
            zen_generated_tokens,
            total_latency_ms,
            total_cost_usd,
        })
    }

    /// Executes Kai-gated selective HyDE retrieval: Kai predicts whether the
    /// query suffers from vocabulary mismatch (`p_expand >= theta`) and only
    /// invokes Zen passage synthesis when needed.
    #[allow(clippy::too_many_arguments)]
    pub fn search_kai_selective(
        &self,
        collection: &str,
        runtime_meta: &IndexEmbeddingMetadata,
        caller: &CallerAccessContext,
        raw_query: &str,
        gate: &KaiHydeGate,
        classifier: &dyn KaiHydeClassifier,
        config: &HydeConfig,
        generator: &dyn ZenHypothesisGenerator,
        embedder: &dyn PrefixedTextEmbedder,
        cost_model: &HydeCostModel,
    ) -> Result<HydeSearchOutcome, HydeError> {
        if raw_query.trim().is_empty() {
            return Err(HydeError::EmptyQuery);
        }
        cost_model.validate()?;
        let probs = classifier.classify_query(raw_query)?;
        let decision = gate.decide(probs);

        let mut outcome = match decision.action {
            HydeRouteAction::HydeExpanded => self.search_hyde(
                collection,
                runtime_meta,
                caller,
                raw_query,
                config,
                generator,
                embedder,
                cost_model,
            )?,
            HydeRouteAction::QueryOnly => self.search_query_only(
                collection,
                runtime_meta,
                caller,
                raw_query,
                config.top_k,
                embedder,
                cost_model,
            )?,
        };
        outcome.kai_decision = Some(decision);
        outcome.total_cost_usd += cost_model.kai_gate_cost_usd;
        outcome.total_latency_ms += cost_model.kai_gate_latency_ms;
        Ok(outcome)
    }

    fn rank_authorized_records(
        &self,
        collection: &str,
        caller: &CallerAccessContext,
        probe: &[f32],
        top_k: usize,
    ) -> Vec<HydeScoredHit> {
        let Some(bucket) = self.records.get(collection) else {
            return Vec::new();
        };

        let mut scored: Vec<HydeScoredHit> = bucket
            .iter()
            .filter(|rec| is_authorized(rec, caller))
            .map(|rec| {
                let score: f32 = rec.vector.iter().zip(probe.iter()).map(|(&a, &b)| a * b).sum();
                HydeScoredHit {
                    doc_id: rec.doc_id.clone(),
                    source_revision: rec.source_revision.clone(),
                    score,
                    raw_text: rec.raw_text.clone(),
                }
            })
            .collect();

        scored.sort_by(|a, b| {
            b.score
                .partial_cmp(&a.score)
                .unwrap_or(std::cmp::Ordering::Equal)
                .then_with(|| a.doc_id.cmp(&b.doc_id))
        });
        scored.truncate(top_k);
        scored
    }
}

fn is_authorized(rec: &StoredVectorRecord, caller: &CallerAccessContext) -> bool {
    if rec.tenant_id != caller.tenant_id {
        return false;
    }
    if rec.allowed_roles.is_empty() {
        return true;
    }
    rec.allowed_roles.iter().any(|allowed| caller.roles.iter().any(|r| r == allowed))
}

fn reject_pre_swapped_prefix(
    raw_text: &str,
    expected_prefix: &str,
    other_prefix: &str,
    operation: IndexOperation,
    expected_field: MetadataField,
    actual_field: MetadataField,
) -> Result<(), MetadataError> {
    if !other_prefix.is_empty()
        && other_prefix != expected_prefix
        && raw_text.starts_with(other_prefix)
    {
        return Err(MetadataError::SwappedTaskPrefix {
            operation,
            expected_field,
            expected_prefix: expected_prefix.to_string(),
            actual_field,
            actual_prefix: other_prefix.to_string(),
        });
    }
    Ok(())
}

fn estimate_tokens(text: &str) -> usize {
    let words = text.split_whitespace().count();
    ((words * 4).div_ceil(3)).max(1)
}

