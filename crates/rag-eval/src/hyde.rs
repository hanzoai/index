/// Query slice kind used to separate conceptual vocabulary-mismatch queries from
/// exact symbol / identifier queries (the documented HyDE failure mode).
#[derive(Debug, Clone, Copy, PartialEq, Eq, Serialize, Deserialize)]
#[serde(rename_all = "snake_case")]
pub enum HydeQuerySlice {
    /// Paraphrased / natural-language query using user vocabulary rather than doc terms.
    VocabularyMismatch,
    /// Exact code identifier, error code, or config key where raw tokens are exact.
    ExactIdentifier,
}

/// Single labeled retrieval benchmark query.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
pub struct HydeBenchmarkCase {
    pub case_id: String,
    pub slice: HydeQuerySlice,
    pub raw_query: String,
    pub relevant_doc_ids: Vec<String>,
}

/// Strategy compared in `evaluate_hyde_benchmark`.
#[derive(Debug, Clone, Copy, PartialEq, Serialize, Deserialize)]
#[serde(rename_all = "snake_case")]
pub enum HydeBenchmarkStrategy {
    QueryOnly,
    AlwaysHydePassageOnly { num_hypotheses: usize },
    AlwaysHydeAnchored { num_hypotheses: usize, query_anchor_weight: f32 },
    KaiSelectiveHyde { num_hypotheses: usize, query_anchor_weight: f32, theta: f64 },
}

/// Aggregated recall, ranking, latency, and dollar-cost metrics for one strategy.
#[derive(Debug, Clone, PartialEq, Serialize, Deserialize)]
pub struct HydeStrategyReport {
    pub strategy: HydeBenchmarkStrategy,
    pub query_count: usize,
    pub recall_at_1: f64,
    pub recall_at_3: f64,
    pub mrr: f64,
    pub ndcg_at_3: f64,
    pub vocab_mismatch_recall_at_3: f64,
    pub exact_identifier_recall_at_1: f64,
    pub hyde_expansion_rate: f64,
    pub total_embed_calls: usize,
    pub total_zen_tokens: usize,
    pub mean_latency_ms: f64,
    pub total_cost_usd: f64,
}

/// Runs a reproducible matched-baseline comparison across strategies on the same
/// `HydeIndex` collection, `CallerAccessContext`, `top_k`, and `HydeCostModel`.
#[allow(clippy::too_many_arguments)]
pub fn evaluate_hyde_benchmark(
    index: &HydeIndex,
    collection: &str,
    runtime_meta: &IndexEmbeddingMetadata,
    caller: &CallerAccessContext,
    cases: &[HydeBenchmarkCase],
    strategies: &[HydeBenchmarkStrategy],
    classifier: &dyn KaiHydeClassifier,
    generator: &dyn ZenHypothesisGenerator,
    embedder: &dyn PrefixedTextEmbedder,
    cost_model: &HydeCostModel,
) -> Result<Vec<HydeStrategyReport>, HydeError> {
    if cases.is_empty() {
        return Err(HydeError::EmptyBenchmarkSuite);
    }
    cost_model.validate()?;

    let mut reports = Vec::with_capacity(strategies.len());
    for &strategy in strategies {
        let mut r1_sum = 0.0_f64;
        let mut r3_sum = 0.0_f64;
        let mut mrr_sum = 0.0_f64;
        let mut ndcg3_sum = 0.0_f64;
        let mut vocab_r3_sum = 0.0_f64;
        let mut vocab_count = 0usize;
        let mut exact_r1_sum = 0.0_f64;
        let mut exact_count = 0usize;
        let mut expanded_count = 0usize;
        let mut total_embed_calls = 0usize;
        let mut total_zen_tokens = 0usize;
        let mut total_latency_ms = 0.0_f64;
        let mut total_cost_usd = 0.0_f64;

        for case in cases {
            let outcome = match strategy {
                HydeBenchmarkStrategy::QueryOnly => index.search_query_only(
                    collection,
                    runtime_meta,
                    caller,
                    &case.raw_query,
                    3,
                    embedder,
                    cost_model,
                )?,
                HydeBenchmarkStrategy::AlwaysHydePassageOnly { num_hypotheses } => {
                    let cfg = HydeConfig { num_hypotheses, query_anchor_weight: 0.0, top_k: 3 };
                    index.search_hyde(
                        collection,
                        runtime_meta,
                        caller,
                        &case.raw_query,
                        &cfg,
                        generator,
                        embedder,
                        cost_model,
                    )?
                }
                HydeBenchmarkStrategy::AlwaysHydeAnchored {
                    num_hypotheses,
                    query_anchor_weight,
                } => {
                    let cfg = HydeConfig { num_hypotheses, query_anchor_weight, top_k: 3 };
                    index.search_hyde(
                        collection,
                        runtime_meta,
                        caller,
                        &case.raw_query,
                        &cfg,
                        generator,
                        embedder,
                        cost_model,
                    )?
                }
                HydeBenchmarkStrategy::KaiSelectiveHyde {
                    num_hypotheses,
                    query_anchor_weight,
                    theta,
                } => {
                    let gate = KaiHydeGate::new(theta)?;
                    let cfg = HydeConfig { num_hypotheses, query_anchor_weight, top_k: 3 };
                    index.search_kai_selective(
                        collection,
                        runtime_meta,
                        caller,
                        &case.raw_query,
                        &gate,
                        classifier,
                        &cfg,
                        generator,
                        embedder,
                        cost_model,
                    )?
                }
            };

            let hit_ids: Vec<&str> = outcome.hits.iter().map(|h| h.doc_id.as_str()).collect();
            let hit_at_1 =
                hit_ids.first().is_some_and(|id| case.relevant_doc_ids.iter().any(|r| r == id));
            let hit_at_3 =
                hit_ids.iter().take(3).any(|id| case.relevant_doc_ids.iter().any(|r| r == id));

            let rr = hit_ids
                .iter()
                .position(|id| case.relevant_doc_ids.iter().any(|r| r == id))
                .map_or(0.0, |idx| 1.0 / ((idx + 1) as f64));

            let dcg3: f64 = hit_ids
                .iter()
                .take(3)
                .enumerate()
                .map(|(idx, id)| {
                    if case.relevant_doc_ids.iter().any(|r| r == id) {
                        1.0 / ((idx as f64) + 2.0).log2()
                    } else {
                        0.0
                    }
                })
                .sum();
            let ideal_hits = case.relevant_doc_ids.len().clamp(1, 3);
            let idcg3: f64 = (0..ideal_hits).map(|idx| 1.0 / ((idx as f64) + 2.0).log2()).sum();
            let ndcg3 = if idcg3 > 0.0 { dcg3 / idcg3 } else { 0.0 };

            if hit_at_1 {
                r1_sum += 1.0;
            }
            if hit_at_3 {
                r3_sum += 1.0;
            }
            mrr_sum += rr;
            ndcg3_sum += ndcg3;

            match case.slice {
                HydeQuerySlice::VocabularyMismatch => {
                    vocab_count += 1;
                    if hit_at_3 {
                        vocab_r3_sum += 1.0;
                    }
                }
                HydeQuerySlice::ExactIdentifier => {
                    exact_count += 1;
                    if hit_at_1 {
                        exact_r1_sum += 1.0;
                    }
                }
            }

            if outcome.route_action == HydeRouteAction::HydeExpanded {
                expanded_count += 1;
            }
            total_embed_calls += outcome.embed_calls;
            total_zen_tokens += outcome.zen_generated_tokens;
            total_latency_ms += outcome.total_latency_ms;
            total_cost_usd += outcome.total_cost_usd;
        }

        let n = cases.len() as f64;
        reports.push(HydeStrategyReport {
            strategy,
            query_count: cases.len(),
            recall_at_1: r1_sum / n,
            recall_at_3: r3_sum / n,
            mrr: mrr_sum / n,
            ndcg_at_3: ndcg3_sum / n,
            vocab_mismatch_recall_at_3: if vocab_count > 0 {
                vocab_r3_sum / (vocab_count as f64)
            } else {
                0.0
            },
            exact_identifier_recall_at_1: if exact_count > 0 {
                exact_r1_sum / (exact_count as f64)
            } else {
                0.0
            },
            hyde_expansion_rate: (expanded_count as f64) / n,
            total_embed_calls,
            total_zen_tokens,
            mean_latency_ms: total_latency_ms / n,
            total_cost_usd,
        });
    }

    Ok(reports)
}

/// Deterministic feature-hashing asymmetric embedder used in offline reproducible
/// evaluations. Validates task prefixes (`query_prefix` vs `doc_prefix`) and
/// projects normalized token unigrams and bigrams onto a unit L2 sphere.
#[derive(Debug, Clone, Default)]
pub struct DeterministicHashedEmbedder;

impl PrefixedTextEmbedder for DeterministicHashedEmbedder {
    fn embed_prefixed(
        &self,
        prefixed_text: &str,
        operation: IndexOperation,
        metadata: &IndexEmbeddingMetadata,
    ) -> Result<Vec<f32>, HydeError> {
        metadata.validate_prefixed_text(prefixed_text, operation)?;
        let prefix = match operation {
            IndexOperation::Insert => metadata.doc_prefix.as_str(),
            IndexOperation::Query => metadata.query_prefix.as_str(),
            IndexOperation::Create => "",
        };
        let body = prefixed_text.strip_prefix(prefix).unwrap_or(prefixed_text);
        let dims = metadata.dimensions;
        let mut vec = vec![0.0_f32; dims];

        let tokens = tokenize_preserve_identifiers(body);
        for tok in &tokens {
            accumulate_hash_feature(&mut vec, tok.as_bytes(), 1.0);
        }
        for pair in tokens.windows(2) {
            let bigram = format!("{}_{}", pair[0], pair[1]);
            accumulate_hash_feature(&mut vec, bigram.as_bytes(), 0.65);
        }

        // Ensure deterministic non-zero unit vector even on punctuation-only inputs.
        let norm_sq: f64 = vec.iter().map(|&v| f64::from(v) * f64::from(v)).sum();
        if norm_sq <= 1e-12 {
            vec[0] = 1.0;
        } else if metadata.normalization == NormalizationPolicy::L2 {
            let norm = norm_sq.sqrt() as f32;
            for v in &mut vec {
                *v /= norm;
            }
        }
        Ok(vec)
    }
}

/// Structural Kai query classifier detecting whether a query contains exact code
/// identifiers (`::`, `_`, camelCase, error codes) versus natural-language
/// conceptual phrasing that benefits from HyDE expansion.
#[derive(Debug, Clone, Default)]
pub struct StructuralKaiHydeClassifier;

impl KaiHydeClassifier for StructuralKaiHydeClassifier {
    fn classify_query(&self, raw_query: &str) -> Result<KaiHydeProbs, HydeError> {
        let trimmed = raw_query.trim();
        if trimmed.is_empty() {
            return Err(HydeError::EmptyQuery);
        }
        let has_scope_or_snake = trimmed.contains("::") || trimmed.contains('_');
        let has_error_or_hex = trimmed.split_whitespace().any(|w| {
            let clean = w.trim_matches(|c: char| !c.is_ascii_alphanumeric() && c != '_');
            clean.starts_with("0x")
                || clean.starts_with("ERR")
                || (clean.chars().any(|c| c.is_ascii_uppercase())
                    && clean.chars().any(|c| c.is_ascii_lowercase())
                    && clean.len() >= 6)
        });

        let (logit_expand, logit_query_only) =
            if has_scope_or_snake || has_error_or_hex { (-1.9, 1.9) } else { (1.7, -1.7) };
        KaiHydeProbs::from_logits(logit_expand, logit_query_only)
    }
}

const EMBED_STOPWORDS: &[&str] = &[
    "an", "and", "are", "as", "at", "be", "by", "can", "do", "does", "for", "from", "how", "if",
    "in", "into", "is", "it", "of", "on", "or", "our", "so", "that", "the", "their", "this", "to",
    "up", "use", "uses", "using", "was", "we", "what", "when", "where", "which", "while", "with",
    "without",
];

fn tokenize_preserve_identifiers(text: &str) -> Vec<String> {
    text.split(|c: char| !c.is_ascii_alphanumeric() && c != '_' && c != ':')
        .map(|part| part.trim_matches(':').to_ascii_lowercase())
        .filter(|tok| tok.len() >= 2 && EMBED_STOPWORDS.binary_search(&tok.as_str()).is_err())
        .collect()
}

fn accumulate_hash_feature(vec: &mut [f32], bytes: &[u8], weight: f32) {
    // FNV-1a 64-bit deterministic hash (zero platform variance).
    let mut hash: u64 = 0xcbf29ce484222325;
    for &b in bytes {
        hash ^= u64::from(b);
        hash = hash.wrapping_mul(0x100000001b3);
    }
    let idx = (hash as usize) % vec.len();
    let sign = if (hash >> 63) == 0 { 1.0_f32 } else { -1.0_f32 };
    vec[idx] += sign * weight;
}

