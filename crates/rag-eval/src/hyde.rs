/// Discrete routing action chosen for a retrieval request.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Serialize, Deserialize)]
#[serde(rename_all = "snake_case")]
pub enum HydeRouteAction {
    /// Encode `query_prefix + query` directly with zero Zen generation overhead.
    QueryOnly,
    /// Synthesize ephemeral passages with Zen and probe with prefix-validated centroid.
    HydeExpanded,
}

/// Calibrated discrete probabilities emitted by Kai for selective HyDE routing.
#[derive(Debug, Clone, Copy, PartialEq, Serialize, Deserialize)]
pub struct KaiHydeProbs {
    pub p_expand: f64,
    pub p_query_only: f64,
}

impl KaiHydeProbs {
    /// Validates and normalizes discrete Kai probabilities summing to `1.0`.
    pub fn new(p_expand: f64, p_query_only: f64) -> Result<Self, HydeError> {
        if !p_expand.is_finite()
            || !p_query_only.is_finite()
            || !(0.0..=1.0).contains(&p_expand)
            || !(0.0..=1.0).contains(&p_query_only)
        {
            return Err(HydeError::InvalidProbability { p_expand, p_query_only });
        }
        let sum = p_expand + p_query_only;
        if (sum - 1.0).abs() > 1e-4 {
            return Err(HydeError::ProbabilitiesDoNotSumToOne { sum });
        }
        Ok(Self { p_expand: p_expand / sum, p_query_only: p_query_only / sum })
    }

    /// Constructs normalized Kai probabilities from binary logits via stable softmax.
    pub fn from_logits(logit_expand: f64, logit_query_only: f64) -> Result<Self, HydeError> {
        if !logit_expand.is_finite() || !logit_query_only.is_finite() {
            return Err(HydeError::InvalidProbability {
                p_expand: logit_expand,
                p_query_only: logit_query_only,
            });
        }
        let max_l = logit_expand.max(logit_query_only);
        let e_exp = (logit_expand - max_l).exp();
        let e_q = (logit_query_only - max_l).exp();
        let denom = e_exp + e_q;
        Ok(Self { p_expand: e_exp / denom, p_query_only: e_q / denom })
    }
}

/// Non-generative Kai classifier estimating terminology mismatch on a raw query.
pub trait KaiHydeClassifier: Send + Sync {
    fn classify_query(&self, raw_query: &str) -> Result<KaiHydeProbs, HydeError>;
}

/// Structured Kai decision output for selective HyDE routing.
#[derive(Debug, Clone, Copy, PartialEq, Serialize, Deserialize)]
pub struct KaiHydeDecision {
    pub decision_head: DecisionHead,
    pub action: HydeRouteAction,
    pub p_expand: f64,
    pub p_query_only: f64,
    pub theta: f64,
}

/// Threshold gate converting Kai probabilities into `HydeRouteAction`.
#[derive(Debug, Clone, Copy, PartialEq, Serialize, Deserialize)]
pub struct KaiHydeGate {
    theta: f64,
}

impl KaiHydeGate {
    /// Creates a calibrated Kai selective HyDE gate with `theta` in `[0.0, 1.0]`.
    pub fn new(theta: f64) -> Result<Self, HydeError> {
        if !theta.is_finite() || !(0.0..=1.0).contains(&theta) {
            return Err(HydeError::InvalidThreshold(theta));
        }
        Ok(Self { theta })
    }

    /// Returns the configured expansion threshold `theta`.
    pub fn theta(&self) -> f64 {
        self.theta
    }

    /// Evaluates Kai probabilities without performing any text generation.
    pub fn decide(&self, probs: KaiHydeProbs) -> KaiHydeDecision {
        let action = if probs.p_expand >= self.theta {
            HydeRouteAction::HydeExpanded
        } else {
            HydeRouteAction::QueryOnly
        };
        KaiHydeDecision {
            decision_head: DecisionHead::Kai,
            action,
            p_expand: probs.p_expand,
            p_query_only: probs.p_query_only,
            theta: self.theta,
        }
    }
}

/// Configuration for HyDE passage synthesis and centroid construction.
#[derive(Debug, Clone, Copy, PartialEq, Serialize, Deserialize)]
pub struct HydeConfig {
    /// Number of hypothetical passages synthesized by Zen (`>= 1`).
    pub num_hypotheses: usize,
    /// Weight in `[0.0, 1.0]` assigned to the `query_prefix` query embedding when
    /// forming the normalized HyDE centroid (`0.0` = pure passage centroid;
    /// `0.25..=0.50` = query-anchored centroid preserving exact identifiers).
    pub query_anchor_weight: f32,
    /// Maximum number of ranked hits to return (`>= 1`).
    pub top_k: usize,
}

impl HydeConfig {
    /// Validates `HydeConfig` invariants.
    pub fn validate(&self) -> Result<(), HydeError> {
        if self.num_hypotheses == 0 {
            return Err(HydeError::ZeroHypotheses);
        }
        if self.top_k == 0 {
            return Err(HydeError::ZeroTopK);
        }
        if !self.query_anchor_weight.is_finite() || !(0.0..=1.0).contains(&self.query_anchor_weight)
        {
            return Err(HydeError::InvalidQueryAnchorWeight(self.query_anchor_weight));
        }
        Ok(())
    }
}

impl Default for HydeConfig {
    fn default() -> Self {
        Self { num_hypotheses: 2, query_anchor_weight: 0.30, top_k: 5 }
    }
}

/// Explicit latency and dollar cost parameters for matched-baseline evaluation.
#[derive(Debug, Clone, Copy, PartialEq, Serialize, Deserialize)]
pub struct HydeCostModel {
    pub embed_cost_per_1k_tokens_usd: f64,
    pub embed_latency_ms_per_call: f64,
    pub index_search_latency_ms: f64,
    pub zen_input_cost_per_1k_tokens_usd: f64,
    pub zen_output_cost_per_1k_tokens_usd: f64,
    pub kai_gate_cost_usd: f64,
    pub kai_gate_latency_ms: f64,
}

impl HydeCostModel {
    /// Validates that all cost and latency parameters are finite and non-negative.
    pub fn validate(&self) -> Result<(), HydeError> {
        let fields = [
            ("embed_cost_per_1k_tokens_usd", self.embed_cost_per_1k_tokens_usd),
            ("embed_latency_ms_per_call", self.embed_latency_ms_per_call),
            ("index_search_latency_ms", self.index_search_latency_ms),
            ("zen_input_cost_per_1k_tokens_usd", self.zen_input_cost_per_1k_tokens_usd),
            ("zen_output_cost_per_1k_tokens_usd", self.zen_output_cost_per_1k_tokens_usd),
            ("kai_gate_cost_usd", self.kai_gate_cost_usd),
            ("kai_gate_latency_ms", self.kai_gate_latency_ms),
        ];
        for (name, val) in fields {
            if !val.is_finite() || val < 0.0 {
                return Err(HydeError::InvalidCostParameter(name));
            }
        }
        Ok(())
    }
}

impl Default for HydeCostModel {
    fn default() -> Self {
        Self {
            embed_cost_per_1k_tokens_usd: 0.02,
            embed_latency_ms_per_call: 4.5,
            index_search_latency_ms: 2.0,
            zen_input_cost_per_1k_tokens_usd: 0.15,
            zen_output_cost_per_1k_tokens_usd: 0.60,
            kai_gate_cost_usd: 0.000004,
            kai_gate_latency_ms: 1.2,
        }
    }
}

/// Errors produced by `HydeIndex` indexing, prefix validation, or retrieval.
#[derive(Debug, Error, Clone, PartialEq)]
pub enum HydeError {
    #[error("query must not be empty")]
    EmptyQuery,
    #[error("`doc_id` must not be empty")]
    EmptyDocId,
    #[error("`tenant_id` must not be empty")]
    EmptyTenantId,
    #[error("`num_hypotheses` must be at least 1")]
    ZeroHypotheses,
    #[error("`top_k` must be at least 1")]
    ZeroTopK,
    #[error("`query_anchor_weight`={0} must be finite and in [0.0, 1.0]")]
    InvalidQueryAnchorWeight(f32),
    #[error("threshold `theta`={0} must be finite and in [0.0, 1.0]")]
    InvalidThreshold(f64),
    #[error("invalid Kai probabilities (p_expand={p_expand}, p_query_only={p_query_only})")]
    InvalidProbability { p_expand: f64, p_query_only: f64 },
    #[error("Kai probabilities must sum to 1.0 (got {sum:.6})")]
    ProbabilitiesDoNotSumToOne { sum: f64 },
    #[error("cost parameter `{0}` must be finite and non-negative")]
    InvalidCostParameter(&'static str),
    #[error("Zen returned empty hypothetical passage at index {index}")]
    EmptyHypotheticalPassage { index: usize },
    #[error("Zen returned {actual} hypotheses when {expected} were requested")]
    HypothesisCountMismatch { expected: usize, actual: usize },
    #[error("synthetic Zen passage `{doc_id}` is ephemeral and cannot be inserted into a canonical index")]
    EphemeralHypothesisInsertForbidden { doc_id: String },
    #[error("combined HyDE probe centroid collapsed to zero norm")]
    ZeroCentroidNorm,
    #[error("benchmark suite requires at least one query case")]
    EmptyBenchmarkSuite,
    #[error(transparent)]
    Metadata(#[from] MetadataError),
}

