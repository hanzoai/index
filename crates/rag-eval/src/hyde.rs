/// Origin classification preventing ephemeral Zen hypotheses from polluting a
/// canonical source document index.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Serialize, Deserialize)]
#[serde(rename_all = "snake_case")]
pub enum DocumentOrigin {
    /// Verified source document, blob, commit, or record with stable identity.
    CanonicalSource,
    /// Ephemeral synthetic passage generated by Zen for query-time probing only.
    SyntheticHypothesis,
}

/// Source document submitted for indexing in `HydeIndex`.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
pub struct HydeDocument {
    pub doc_id: String,
    pub source_revision: String,
    pub tenant_id: String,
    /// Optional role allowlist. Empty means all authenticated callers in `tenant_id`.
    pub allowed_roles: Vec<String>,
    pub origin: DocumentOrigin,
    pub raw_text: String,
}

